-- Add teacher-owned custom decks and immutable match snapshots.
-- Existing match and result records remain readable and are never rewritten.
BEGIN;
SELECT pg_advisory_xact_lock(548911, 1);

CREATE TABLE IF NOT EXISTS public.typetiles_schema_migrations (
  version TEXT PRIMARY KEY,
  applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

DO $migration$
DECLARE
  sequence_name TEXT;
  relation_name TEXT;
BEGIN
  IF EXISTS (
    SELECT 1 FROM public.typetiles_schema_migrations
    WHERE version = '20261123000100'
  ) THEN
    RAISE NOTICE 'Type Tiles custom decks migration is already applied; no changes made.';
    RETURN;
  END IF;

  FOREACH relation_name IN ARRAY ARRAY['custom_decks', 'custom_deck_items'] LOOP
    IF to_regclass(format('public.%I', relation_name)) IS NOT NULL THEN
      RAISE EXCEPTION 'public.% already exists without the custom decks migration marker. Stop and review the existing schema.', relation_name;
    END IF;
  END LOOP;

  CREATE TABLE IF NOT EXISTS public.custom_decks (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    practice_format TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'active'
      CHECK (status IN ('active', 'archived')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
  );

  CREATE TABLE IF NOT EXISTS public.custom_deck_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    deck_id INTEGER NOT NULL REFERENCES public.custom_decks(id) ON DELETE CASCADE,
    prompt TEXT,
    answer TEXT NOT NULL,
    sort_order INTEGER NOT NULL,
    UNIQUE (deck_id, sort_order)
  );

  CREATE INDEX IF NOT EXISTS custom_decks_teacher_status
    ON public.custom_decks(teacher_user_id, status);
  CREATE INDEX IF NOT EXISTS custom_deck_items_deck_order
    ON public.custom_deck_items(deck_id, sort_order);

  ALTER TABLE public.matches
    ADD COLUMN IF NOT EXISTS custom_deck_id INTEGER
      REFERENCES public.custom_decks(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS custom_deck_snapshot JSONB;

  ALTER TABLE public.custom_decks ENABLE ROW LEVEL SECURITY;
  ALTER TABLE public.custom_deck_items ENABLE ROW LEVEL SECURITY;
  REVOKE ALL ON TABLE public.custom_decks FROM PUBLIC, anon, authenticated;
  REVOKE ALL ON TABLE public.custom_deck_items FROM PUBLIC, anon, authenticated;

  sequence_name := pg_get_serial_sequence('public.custom_decks', 'id');
  IF sequence_name IS NOT NULL THEN
    EXECUTE format('REVOKE ALL ON SEQUENCE %s FROM PUBLIC, anon, authenticated', sequence_name);
  END IF;
  sequence_name := pg_get_serial_sequence('public.custom_deck_items', 'id');
  IF sequence_name IS NOT NULL THEN
    EXECUTE format('REVOKE ALL ON SEQUENCE %s FROM PUBLIC, anon, authenticated', sequence_name);
  END IF;

  INSERT INTO public.typetiles_schema_migrations(version)
  VALUES ('20261123000100');
END
$migration$;

COMMIT;
